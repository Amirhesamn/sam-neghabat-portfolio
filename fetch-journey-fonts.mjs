// Self-hosts the storybook fonts (Varela Round + Nunito Sans) for the /journey page,
// so typography never depends on fonts.gstatic.com (blocked/reset on some networks).
import { mkdir, writeFile } from 'node:fs/promises';

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Nunito+Sans:wght@400;600;700;800&family=Varela+Round&display=swap';
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const OUT = new URL('./src/journey/fonts/', import.meta.url);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function withRetry(fn, label, tries = 6) {
  let last;
  for (let i = 0; i < tries; i++) {
    try { return await fn(); }
    catch (e) { last = e; process.stdout.write(`  retry ${i + 1}/${tries} ${label} (${e.message})\n`); await sleep(700 + i * 500); }
  }
  throw last;
}

async function main() {
  await mkdir(OUT, { recursive: true });
  const css = await withRetry(async () => {
    const res = await fetch(CSS_URL, { headers: { 'User-Agent': UA } });
    if (!res.ok) throw new Error('css ' + res.status);
    return res.text();
  }, 'css');

  const blocks = css.split('@font-face').filter((b) => b.includes('url('));
  let out = '/* self-hosted storybook fonts — generated by fetch-journey-fonts.mjs */\n';
  const counters = {};
  let n = 0;
  for (const b of blocks) {
    const fam = (b.match(/font-family:\s*'([^']+)'/) || [])[1] || 'font';
    const weight = (b.match(/font-weight:\s*([^;]+);/) || [])[1]?.trim() || '400';
    const style = (b.match(/font-style:\s*([^;]+);/) || [])[1]?.trim() || 'normal';
    const url = (b.match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/) || [])[1];
    const range = (b.match(/unicode-range:\s*([^;]+);/) || [])[1]?.trim() || '';
    if (!url) continue;
    const slug = fam.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    counters[slug] = (counters[slug] || 0) + 1;
    const file = `${slug}-${weight}-${counters[slug]}.woff2`;
    const buf = await withRetry(async () => {
      const r = await fetch(url, { headers: { 'User-Agent': UA } });
      if (!r.ok) throw new Error('font ' + r.status);
      return Buffer.from(await r.arrayBuffer());
    }, file);
    await writeFile(new URL(file, OUT), buf);
    n++;
    out += `@font-face{font-family:'${fam}';font-style:${style};font-weight:${weight};font-display:swap;src:url('./${file}') format('woff2');${range ? `unicode-range:${range};` : ''}}\n`;
  }
  await writeFile(new URL('./fonts.css', OUT), out);
  console.log(`Done — ${n} font files saved to src/journey/fonts/.`);
}
main().catch((e) => { console.error('failed:', e.message); process.exit(1); });
